/**
 * Дозакрытие недописанного ответа.
 *
 * Пока ответ течёт, в тексте висят незакрытые конструкции: открытый блок кода,
 * одинокая пара звёздочек, начатая строка таблицы. Если отдать это разборщику
 * как есть, на экране мигают то сырые звёздочки, то разъезжающаяся вёрстка.
 *
 * Здесь только работа со строкой — ни разбора, ни зависимостей: сам markdown
 * рисует MdPreview (см. preview.js).
 */
export const healPartial = (text) => {
  let s = String(text)

  // Незакрытый блок кода: иначе весь остаток ответа станет кодом.
  const fences = (s.match(/^```/gm) || []).length
  if (fences % 2 === 1) s += '\n```'

  // Недописанная последняя строка таблицы только мигает — отложим до конца.
  const lines = s.split('\n')
  const last = lines[lines.length - 1]
  if (fences % 2 === 0 && /^\s*\|/.test(last) && !/\|\s*$/.test(last)) {
    lines.pop()
    s = lines.join('\n')
  }

  // Непарные ** и ` — чтобы не мелькали символами.
  if (((s.match(/\*\*/g) || []).length) % 2 === 1) s += '**'
  const ticks = (s.match(/`/g) || []).length - (s.match(/```/g) || []).length * 3
  if (ticks % 2 === 1) s += '`'

  return s
}
